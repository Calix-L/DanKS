def test_copy_snapshot_and_manifest_are_sorted_and_content_addressed(tmp_path: Path) -> None:
    repository = tmp_path / "DanKS"
    source = tmp_path / "upstream"
    write_file(source, "z.py", b"z\n")
    write_file(source, "a.py", b"a\n")
    write_file(source, "README.md", b"private docs\n")
    destination = repository / "generations" / "v1" / "source"

    copied = copy_snapshot(source, destination, repository)
    assert [path.as_posix() for path in copied] == ["a.py", "z.py"]
    assert not (destination / "README.md").exists()

    manifest_path = write_generation_manifest(
        repository,
        "v1",
        source_label="frozen-source-snapshot",
    )
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["generation"] == "v1"
    assert manifest["source"] == "frozen-source-snapshot"
    assert "upstream" not in manifest_path.read_text(encoding="utf-8")
    assert [item["path"] for item in manifest["files"]] == ["a.py", "z.py"]
    assert manifest["files"][0] == {
        "path": "a.py",
        "sha256": hashlib.sha256(b"a\n").hexdigest(),
        "size": 2,
    }
    assert sha256_file(destination / "z.py") == hashlib.sha256(b"z\n").hexdigest()


