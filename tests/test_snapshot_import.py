def test_collect_source_files_does_not_follow_symlinks(tmp_path: Path) -> None:
    if not hasattr(os, "symlink"):
        pytest.skip("symlinks are unavailable")

    source = tmp_path / "source"
    outside = write_file(tmp_path, "outside/secret.py", b"private\n")
    write_file(source, "pkg/real.py")
    (source / "linked.py").symlink_to(outside)
    (source / "linked_dir").symlink_to(outside.parent, target_is_directory=True)

    assert [path.as_posix() for path in collect_source_files(source)] == ["pkg/real.py"]


