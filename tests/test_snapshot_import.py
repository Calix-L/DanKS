def test_copy_snapshot_can_sanitize_private_path_prefixes(tmp_path: Path) -> None:
    repository = tmp_path / "DanKS"
    source = tmp_path / "source"
    write_file(
        source,
        "pkg/paths.py",
        b'linux = "/srv/private/alice/project"\nmac = "/Users/alice/project"\n',
    )
    destination = repository / "generations" / "v3" / "source"

    copy_snapshot(
        source,
        destination,
        repository,
        text_replacements={
            b"/srv/private/alice": b"/workspace/danks",
            b"/Users/alice": b"/workspace/danks",
        },
    )

    content = (destination / "pkg/paths.py").read_bytes()
    assert b"/home/share/user/" not in content
    assert b"/Users/" not in content
    assert content.count(b"/workspace/danks/project") == 2


def test_importer_builds_anonymous_replacements_from_cli_prefixes() -> None:
    assert build_text_replacements(["/srv/private/alice", "/Users/alice"]) == {
        b"/srv/private/alice": b"/workspace/danks",
        b"/Users/alice": b"/workspace/danks",
    }
    with pytest.raises(ValueError, match="absolute paths"):
        build_text_replacements(["/"])


def test_copy_snapshot_supports_curated_exclusions_and_overlays(tmp_path: Path) -> None:
    repository = tmp_path / "DanKS"
    source = tmp_path / "source"
    overlay = write_file(tmp_path, "overlay/model.py", b"v3 model\n")
    write_file(source, "training/model.py", b"later experimental model\n")
    write_file(source, "training/v13_model.py", b"not part of V3\n")
    write_file(source, "tests/test_v13.py", b"not part of V3\n")
    destination = repository / "generations" / "v3" / "source" / "DanRL_retrieval"

    copied = copy_snapshot(
        source,
        destination,
        repository,
        excluded_relative_paths={"training/v13_model.py", "tests/test_v13.py"},
        overlay_files={"training/model.py": overlay},
    )

    assert [path.as_posix() for path in copied] == ["training/model.py"]
    assert (destination / "training/model.py").read_bytes() == b"v3 model\n"
    assert not (destination / "training/v13_model.py").exists()


def test_v3_public_exclusions_keep_only_supported_core_tests(tmp_path: Path) -> None:
    source = tmp_path / "v3"
    for test_name in V3_INCLUDED_TESTS:
        write_file(source, f"tests/{test_name}")
    write_file(source, "tests/test_platform_danks_training.py")
    write_file(source, "tests/test_v13_structured_tactics.py")
    write_file(source, "training/v13_model.py")

    excluded = v3_excluded_relative_paths(source)

    assert "tests/test_platform_danks_training.py" in excluded
    assert "tests/test_v13_structured_tactics.py" in excluded
    assert "training/v13_model.py" in excluded
    assert not {
        f"tests/{test_name}" for test_name in V3_INCLUDED_TESTS
    } & excluded


